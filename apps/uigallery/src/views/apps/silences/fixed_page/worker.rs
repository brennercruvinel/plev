//! The ffmpeg jobs of the Silences page, off the app's thread (task-69
//! phase 4a): the test video generated when it is missing, the silences
//! detected (`silencedetect`), one frame decoded to png and loaded into
//! the image atlas. Each job is one child process on a thread of its own
//! with a deadline past which it is killed by its pid (the form of
//! `claude-model/src/run.rs`, not a dependency on it), and its result comes
//! back through a channel the page reads from `wake`. One job runs at a
//! time: the queue keeps the order and the machine calm.
//!
//! The program is looked for when the first job runs, never at rest, so
//! the page at rest is the same with or without ffmpeg (the golden, the
//! regression baseline, `--render`). In the crate's own tests it is never
//! looked for: a test points the fake (`Worker::fake`) or the real program
//! (`Worker::real`, the ignored test). Off the desktop (wasm, mobile)
//! there is no process and no thread: every job ends saying so.

use std::collections::VecDeque;
#[cfg(test)]
use std::path::Path;
use std::path::PathBuf;
use std::sync::mpsc::{self, Receiver, TryRecvError};
use std::time::Duration;

use engine::drawing::gpu::image::ImageHandle;
use crate::domain::silences::{Detected, Settings, TEST_VIDEO};

/// How often the page looks at the channel while a job runs.
pub(crate) const POLL: Duration = Duration::from_millis(100);

/// A job for the worker.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) enum Job {
    /// Detect the silences of the test video with these settings.
    Detect(Settings),
    /// Decode the frame at this instant (milliseconds into the video).
    Frame { ms: u64 },
}

/// What a job came to.
#[derive(Debug)]
pub(crate) enum Done {
    Detected {
        with: Settings,
        result: Result<Detected, String>,
        took: Duration,
    },
    Frame {
        ms: u64,
        result: Result<ImageHandle, String>,
        took: Duration,
    },
}

/// What runs the jobs.
enum Program {
    /// ffmpeg, `PLEV_FFMPEG` or the one on the PATH, looked for at the
    /// first job and kept (the path, or why there is none).
    Ffmpeg(Option<Result<PathBuf, String>>),
    /// Nothing is looked for (the crate's tests): every job fails saying
    /// so.
    #[cfg(test)]
    Nothing,
    /// Answers from a fixture, without a process (tests).
    #[cfg(test)]
    Fake(Fake),
}

/// The fake worker of the tests: the detection it answers with, and
/// whether it holds its answers until `release`.
#[cfg(test)]
pub(super) struct Fake {
    pub detected: Detected,
    pub hold: bool,
}

pub(crate) struct Worker {
    /// Where the test video is (generated by the first job that needs it).
    video: PathBuf,
    program: Program,
    queue: VecDeque<Job>,
    running: Option<(Job, Receiver<Done>)>,
    /// The answer the fake holds back, until `release`.
    #[cfg(test)]
    held: Option<(Job, mpsc::Sender<Done>)>,
}

impl Worker {
    /// The worker of the app: ffmpeg, looked for at the first job. In the
    /// crate's tests nothing is looked for.
    pub fn new() -> Self {
        #[cfg(not(test))]
        let program = Program::Ffmpeg(None);
        #[cfg(test)]
        let program = Program::Nothing;
        Self::with(program)
    }

    /// The real program, in a test that wants it (`#[ignore]`).
    #[cfg(test)]
    pub fn real() -> Self {
        Self::with(Program::Ffmpeg(None))
    }

    /// The fake: `detected` for every detection, a synthetic frame for
    /// every instant, no process.
    #[cfg(test)]
    pub fn fake(detected: Detected, hold: bool) -> Self {
        Self::with(Program::Fake(Fake { detected, hold }))
    }

    fn with(program: Program) -> Self {
        Self {
            video: temp_dir().join("plev-silences").join(TEST_VIDEO),
            program,
            queue: VecDeque::new(),
            running: None,
            #[cfg(test)]
            held: None,
        }
    }

    /// The test video's path.
    #[cfg(test)]
    pub fn video(&self) -> &Path {
        &self.video
    }

    /// Where ffmpeg is, or why it is not (the ignored test says which
    /// before it runs).
    #[cfg(test)]
    pub fn find_program() -> Result<PathBuf, String> {
        child::find()
    }

    /// True while a job runs or waits.
    pub fn busy(&self) -> bool {
        self.running.is_some() || !self.queue.is_empty()
    }

    /// The job running now.
    pub fn running(&self) -> Option<Job> {
        self.running.as_ref().map(|(job, _)| *job)
    }

    /// True when `job` runs or waits.
    pub fn has(&self, job: Job) -> bool {
        self.running() == Some(job) || self.queue.contains(&job)
    }

    /// Queues `job` (once) and starts it when nothing runs.
    pub fn submit(&mut self, job: Job) {
        if !self.has(job) {
            self.queue.push_back(job);
        }
        self.start_next();
    }

    /// What ended since the last look, in order, and the next job started.
    pub fn poll(&mut self) -> Vec<Done> {
        let mut done = Vec::new();
        while let Some((job, rx)) = self.running.as_ref() {
            let answer = match rx.try_recv() {
                Ok(d) => d,
                Err(TryRecvError::Empty) => break,
                Err(TryRecvError::Disconnected) => gone(*job),
            };
            done.push(answer);
            self.running = None;
            self.start_next();
        }
        done
    }

    /// The fake sends the answer it held.
    #[cfg(test)]
    pub fn release(&mut self) {
        if let Some((job, tx)) = self.held.take() {
            let Program::Fake(fake) = &self.program else {
                return;
            };
            let _ = tx.send(fake.answer(job));
        }
    }

    fn start_next(&mut self) {
        if self.running.is_some() {
            return;
        }
        let Some(job) = self.queue.pop_front() else {
            return;
        };
        let rx = match &mut self.program {
            Program::Ffmpeg(found) => {
                let program = found.get_or_insert_with(child::find).clone();
                match program {
                    Ok(program) => child::spawn(program, self.video.clone(), job),
                    Err(why) => answered(job, why),
                }
            }
            #[cfg(test)]
            Program::Nothing => answered(
                job,
                "ffmpeg is not looked for in the crate's tests".to_owned(),
            ),
            #[cfg(test)]
            Program::Fake(fake) => {
                let (tx, rx) = mpsc::channel();
                if fake.hold {
                    self.held = Some((job, tx));
                } else {
                    let _ = tx.send(fake.answer(job));
                }
                rx
            }
        };
        self.running = Some((job, rx));
    }
}

/// A channel that already holds `job` failed with `why`.
fn answered(job: Job, why: String) -> Receiver<Done> {
    let (tx, rx) = mpsc::channel();
    let _ = tx.send(match job {
        Job::Detect(with) => Done::Detected {
            with,
            result: Err(why),
            took: Duration::ZERO,
        },
        Job::Frame { ms } => Done::Frame {
            ms,
            result: Err(why),
            took: Duration::ZERO,
        },
    });
    rx
}

/// A worker thread that ended without an answer is an answer too.
fn gone(job: Job) -> Done {
    let why = "the worker ended without an answer".to_owned();
    match job {
        Job::Detect(with) => Done::Detected {
            with,
            result: Err(why),
            took: Duration::ZERO,
        },
        Job::Frame { ms } => Done::Frame {
            ms,
            result: Err(why),
            took: Duration::ZERO,
        },
    }
}

#[cfg(test)]
impl Fake {
    fn answer(&self, job: Job) -> Done {
        match job {
            Job::Detect(with) => Done::Detected {
                with,
                result: Ok(self.detected.clone()),
                took: Duration::from_millis(7),
            },
            Job::Frame { ms } => {
                // a 32 by 18 wash whose gray follows the instant, so two
                // instants are two handles
                let (w, h) = (32u32, 18u32);
                let v = u8::try_from(40 + (ms / 100) % 200).unwrap_or(120);
                let pixels = std::iter::repeat_n([v, v, v, 255], (w * h) as usize)
                    .flatten()
                    .collect();
                Done::Frame {
                    ms,
                    result: engine::drawing::gpu::image::load_image_rgba(w, h, pixels)
                        .map_err(|e| e.to_string()),
                    took: Duration::from_millis(3),
                }
            }
        }
    }
}

/// The child processes, on the desktop.
#[cfg(not(any(target_arch = "wasm32", target_os = "android", target_os = "ios")))]
mod child {
    use std::io::{ErrorKind, Read};
    use std::path::{Path, PathBuf};
    use std::process::{Child, Command, ExitStatus, Stdio};
    use std::sync::mpsc::{self, Receiver};
    use std::sync::{Arc, Mutex};
    use std::thread;
    use std::time::{Duration, Instant};

    use engine::drawing::gpu::image::{ImageHandle, load_image_bytes};
    use crate::domain::silences::{Detected, Settings, parse};

    use super::{Done, Job};

    /// How often the child is asked whether it has exited.
    const POLL: Duration = Duration::from_millis(10);
    /// How long the end of its output is waited for once it has exited.
    const GRACE: Duration = Duration::from_secs(1);
    /// The deadlines: generating the test video, a detection, one frame.
    const GENERATE: Duration = Duration::from_secs(30);
    const DETECT: Duration = Duration::from_secs(60);
    const FRAME: Duration = Duration::from_secs(20);
    /// The widest frame decoded, in pixels: the atlas is grow-only, and
    /// the test video is narrower than this anyway.
    const FRAME_MAX_W: u32 = 480;

    /// `PLEV_FFMPEG`, or `ffmpeg` in a directory of the PATH; a file at
    /// that path, without running it.
    pub fn find() -> Result<PathBuf, String> {
        if let Some(named) = std::env::var_os("PLEV_FFMPEG") {
            let path = PathBuf::from(named);
            return if path.is_file() {
                Ok(path)
            } else {
                Err(format!(
                    "PLEV_FFMPEG names {}, which is not a file",
                    path.display()
                ))
            };
        }
        let dirs = std::env::var_os("PATH").unwrap_or_default();
        std::env::split_paths(&dirs)
            .map(|dir| dir.join("ffmpeg"))
            .find(|p| p.is_file())
            .ok_or_else(|| "ffmpeg is not on the PATH (PLEV_FFMPEG names one)".to_owned())
    }

    /// Runs `job` on a thread of its own; the answer comes on the channel.
    pub fn spawn(program: PathBuf, video: PathBuf, job: Job) -> Receiver<Done> {
        let (tx, rx) = mpsc::channel();
        let spawned = thread::Builder::new()
            .name("silences-ffmpeg".to_owned())
            .spawn(move || {
                let started = Instant::now();
                let done = match job {
                    Job::Detect(with) => Done::Detected {
                        with,
                        result: ensure_video(&program, &video)
                            .and_then(|()| detect(&program, &video, with)),
                        took: started.elapsed(),
                    },
                    Job::Frame { ms } => Done::Frame {
                        ms,
                        result: ensure_video(&program, &video)
                            .and_then(|()| frame(&program, &video, ms)),
                        took: started.elapsed(),
                    },
                };
                let _ = tx.send(done);
            });
        if spawned.is_err() {
            return super::answered(job, "could not start a thread for ffmpeg".to_owned());
        }
        rx
    }

    /// The test video of the probe: 12 s of `testsrc` at 320x180, 10 fps,
    /// a 440 Hz sine muted from 3 to 5 s and from 8 to 10 s. Written to a
    /// `.part` beside its place and moved there whole, so a killed run
    /// leaves no half video to reuse.
    fn ensure_video(program: &Path, video: &Path) -> Result<(), String> {
        if video.is_file() {
            return Ok(());
        }
        let dir = video.parent().ok_or("the video has no directory")?;
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        let part = video.with_extension("mp4.part");
        let mut command = Command::new(program);
        command.args([
            "-hide_banner",
            "-nostdin",
            "-y",
            "-v",
            "error",
            "-f",
            "lavfi",
            "-i",
            "testsrc=size=320x180:rate=10",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:sample_rate=44100",
            "-t",
            "12",
            "-af",
            "volume=enable='between(t,3,5)+between(t,8,10)':volume=0",
            "-c:v",
            "libx264",
            "-preset",
            "ultrafast",
            "-crf",
            "28",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            "-b:a",
            "64k",
            "-f",
            "mp4",
        ]);
        command.arg(&part);
        let exit = run(command, program, GENERATE)?;
        if !exit.status.success() {
            let _ = std::fs::remove_file(&part);
            return Err(format!(
                "ffmpeg could not generate the test video: {}",
                tail(&exit.stderr)
            ));
        }
        std::fs::rename(&part, video).map_err(|e| format!("{}: {e}", video.display()))
    }

    /// `silencedetect` over the whole video; the stderr parsed.
    fn detect(program: &Path, video: &Path, with: Settings) -> Result<Detected, String> {
        let with = with.clamped();
        let mut command = Command::new(program);
        command.args([
            "-hide_banner",
            "-nostdin",
            "-nostats",
            "-loglevel",
            "info",
            "-i",
        ]);
        command.arg(video);
        command.args([
            "-af",
            &format!(
                "silencedetect=noise={:.0}dB:d={:.2}",
                with.threshold_db, with.min_duration
            ),
            "-f",
            "null",
            "-",
        ]);
        let exit = run(command, program, DETECT)?;
        if !exit.status.success() {
            return Err(format!("ffmpeg failed: {}", tail(&exit.stderr)));
        }
        let detected = parse(&String::from_utf8_lossy(&exit.stderr));
        if detected.duration.is_none() {
            return Err("ffmpeg printed no duration for the video".to_owned());
        }
        Ok(detected)
    }

    /// One frame at `ms`, as png on stdout, into the image atlas.
    fn frame(program: &Path, video: &Path, ms: u64) -> Result<ImageHandle, String> {
        let mut command = Command::new(program);
        command.args(["-hide_banner", "-nostdin", "-v", "error", "-ss"]);
        command.arg(format!("{:.3}", ms as f64 / 1000.0));
        command.arg("-i");
        command.arg(video);
        command.args([
            "-frames:v",
            "1",
            "-vf",
            &format!("scale='min({FRAME_MAX_W},iw)':-2"),
            "-f",
            "image2",
            "-c:v",
            "png",
            "pipe:1",
        ]);
        let exit = run(command, program, FRAME)?;
        if !exit.status.success() {
            return Err(format!("ffmpeg failed: {}", tail(&exit.stderr)));
        }
        if exit.stdout.is_empty() {
            return Err("ffmpeg produced no image".to_owned());
        }
        load_image_bytes(&exit.stdout).map_err(|e| e.to_string())
    }

    /// The last line of a stderr, for a message.
    fn tail(stderr: &[u8]) -> String {
        let text = String::from_utf8_lossy(stderr);
        text.lines()
            .rev()
            .find(|l| !l.trim().is_empty())
            .unwrap_or("no output")
            .to_owned()
    }

    struct Exit {
        status: ExitStatus,
        stdout: Vec<u8>,
        stderr: Vec<u8>,
    }

    /// A pipe read on a thread of its own, into a buffer shared with the
    /// caller, until its end (a png is bigger than the pipe's buffer).
    struct Drain {
        bytes: Arc<Mutex<Vec<u8>>>,
        end: Receiver<()>,
    }

    impl Drain {
        fn new(from: Option<impl Read + Send + 'static>) -> Drain {
            let bytes = Arc::new(Mutex::new(Vec::new()));
            let (tx, end) = mpsc::channel();
            if let Some(mut from) = from {
                let into = Arc::clone(&bytes);
                thread::spawn(move || {
                    let mut chunk = [0u8; 8192];
                    loop {
                        match from.read(&mut chunk) {
                            Ok(0) => break,
                            Ok(n) => {
                                if let Ok(mut all) = into.lock() {
                                    all.extend_from_slice(&chunk[..n]);
                                }
                            }
                            Err(e) if e.kind() == ErrorKind::Interrupted => {}
                            Err(_) => break,
                        }
                    }
                    let _ = tx.send(());
                });
            }
            Drain { bytes, end }
        }

        /// All of it once the pipe ends, or what came before `until`.
        fn bytes(self, until: Instant) -> Vec<u8> {
            let _ = self
                .end
                .recv_timeout(until.saturating_duration_since(Instant::now()));
            self.bytes.lock().map(|b| b.clone()).unwrap_or_default()
        }
    }

    /// Kills `child` by its pid and reaps it.
    fn kill(child: &mut Child) {
        let _ = child.kill();
        let _ = child.wait();
    }

    /// Runs `command` and waits for it at most `timeout`: past it the
    /// child is killed and the error says so.
    fn run(mut command: Command, program: &Path, timeout: Duration) -> Result<Exit, String> {
        let name = program.display();
        let mut child = command
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(|e| format!("could not start {name}: {e}"))?;
        let pid = child.id();
        let stdout = Drain::new(child.stdout.take());
        let stderr = Drain::new(child.stderr.take());
        let deadline = Instant::now() + timeout;
        let status = loop {
            match child.try_wait() {
                Ok(Some(status)) => break status,
                Ok(None) if Instant::now() >= deadline => {
                    kill(&mut child);
                    return Err(format!(
                        "{name} did not finish in {} s: killed (pid {pid})",
                        timeout.as_secs()
                    ));
                }
                Ok(None) => thread::sleep(POLL),
                Err(e) => {
                    kill(&mut child);
                    return Err(format!("could not wait for {name}: {e}"));
                }
            }
        };
        let until = Instant::now() + GRACE;
        Ok(Exit {
            status,
            stdout: stdout.bytes(until),
            stderr: stderr.bytes(until),
        })
    }
}

/// No process and no thread off the desktop: every job ends saying so.
#[cfg(any(target_arch = "wasm32", target_os = "android", target_os = "ios"))]
mod child {
    use std::path::PathBuf;
    use std::sync::mpsc::Receiver;

    use super::{Done, Job};

    pub fn find() -> Result<PathBuf, String> {
        Err("ffmpeg runs on the desktop only".to_owned())
    }

    pub fn spawn(_program: PathBuf, _video: PathBuf, job: Job) -> Receiver<Done> {
        super::answered(job, "ffmpeg runs on the desktop only".to_owned())
    }
}

/// The system's temporary directory. The web has none: there
/// `std::env::temp_dir` panics (the gallery built for wasm32 died at start
/// building this app), and no program runs there to write the video either.
fn temp_dir() -> PathBuf {
    if cfg!(target_arch = "wasm32") {
        PathBuf::new()
    } else {
        std::env::temp_dir()
    }
}
